package com.crimson.brazilvpn

import android.app.Activity
import android.content.Intent
import android.net.VpnService
import android.os.Bundle
import android.text.InputType
import android.view.Gravity
import android.widget.*
import com.wireguard.android.backend.GoBackend
import com.wireguard.android.backend.Tunnel
import com.wireguard.config.Config
import java.io.ByteArrayInputStream
import java.util.concurrent.Executors

class MainActivity : Activity() {
    private val executor = Executors.newSingleThreadExecutor()
    private lateinit var backend: GoBackend
    private lateinit var status: TextView
    private lateinit var configInput: EditText
    private val tunnel = object : Tunnel {
        override fun getName() = "Brazil"
        override fun onStateChange(newState: Tunnel.State) {
            runOnUiThread { status.text = "Tunnel: $newState" }
        }
    }
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        backend = GoBackend(applicationContext)
        val layout = LinearLayout(this).apply { orientation = LinearLayout.VERTICAL; setPadding(32, 40, 32, 24) }
        layout.addView(TextView(this).apply { text = "Brazil WireGuard VPN"; textSize = 24f; gravity = Gravity.CENTER })
        layout.addView(TextView(this).apply { text = "Paste the private client configuration generated by your Brazil server. Never commit it to GitHub." })
        configInput = EditText(this).apply {
            minLines = 9; maxLines = 14; gravity = Gravity.TOP
            inputType = InputType.TYPE_CLASS_TEXT or InputType.TYPE_TEXT_FLAG_MULTI_LINE or InputType.TYPE_TEXT_VARIATION_VISIBLE_PASSWORD
            setText(getPreferences(MODE_PRIVATE).getString("wg_config", ""))
            hint = "[Interface]..."
        }
        layout.addView(configInput, LinearLayout.LayoutParams(-1, 0, 1f))
        status = TextView(this).apply { text = "Tunnel: DOWN" }
        layout.addView(status)
        layout.addView(Button(this).apply { text = "Connect"; setOnClickListener { connect() } })
        layout.addView(Button(this).apply { text = "Disconnect"; setOnClickListener { changeState(Tunnel.State.DOWN) } })
        layout.addView(Button(this).apply { text = "Save config on device"; setOnClickListener { saveConfig() } })
        layout.addView(TextView(this).apply { text = "For a strict kill switch, enable Always-on VPN and Block connections without VPN in Android Settings." })
        setContentView(layout)
    }
    private fun saveConfig() {
        val raw = configInput.text.toString()
        try {
            Config.parse(ByteArrayInputStream(raw.toByteArray(Charsets.UTF_8)))
            getPreferences(MODE_PRIVATE).edit().putString("wg_config", raw).apply()
            status.text = "Configuration saved on device"
        } catch (e: Exception) { status.text = "Invalid configuration: ${e.message}" }
    }
    private fun connect() {
        try { Config.parse(ByteArrayInputStream(configInput.text.toString().toByteArray())) }
        catch (e: Exception) { status.text = "Invalid configuration: ${e.message}"; return }
        val intent = VpnService.prepare(this)
        if (intent != null) startActivityForResult(intent, 42) else changeState(Tunnel.State.UP)
    }
    @Deprecated("Legacy result callback for broad Android support")
    override fun onActivityResult(requestCode: Int, resultCode: Int, data: Intent?) {
        super.onActivityResult(requestCode, resultCode, data)
        if (requestCode == 42 && resultCode == RESULT_OK) changeState(Tunnel.State.UP)
        else if (requestCode == 42) status.text = "VPN permission denied"
    }
    private fun changeState(state: Tunnel.State) {
        val raw = configInput.text.toString()
        status.text = "Tunnel: ${if (state == Tunnel.State.UP) "CONNECTING" else "DISCONNECTING"}"
        executor.execute {
            try {
                val config = if (state == Tunnel.State.UP) Config.parse(ByteArrayInputStream(raw.toByteArray())) else null
                backend.setState(tunnel, state, config)
                runOnUiThread { status.text = "Tunnel: $state" }
            } catch (e: Exception) { runOnUiThread { status.text = "VPN error: ${e.message}" } }
        }
    }
    override fun onDestroy() { executor.shutdown(); super.onDestroy() }
}
